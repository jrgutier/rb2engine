def test_never_inserts_performance_data_directly(conn: sqlite3.Connection) -> None:
    """Guard: writer must only UPDATE PerformanceData; the trigger owns INSERT.

    A second INSERT would violate trackId PK. We pin the UPDATE helper's SQL
    (no INSERT) and assert a 1:1 Track↔PerformanceData cardinality with blobs
    filled — trigger-only would leave trackData NULL; double-insert would raise.
    """
    import inspect

    import rb2engine.writer.tracks as tracks_mod

    update_src = inspect.getsource(tracks_mod._update_performance_data)
    assert "UPDATE PerformanceData" in update_src
    # The UPDATE helper must not contain an INSERT statement.
    body_sql = [
        ln
        for ln in update_src.splitlines()
        if "INSERT" in ln.upper() and not ln.strip().startswith(("#", '"""', "'''"))
    ]
    assert body_sql == [], f"UPDATE helper must not INSERT: {body_sql}"

    insert_tracks(
        conn,
        [
            _make_track(),
            _make_track(path="../Contents/Artist/Other.mp3"),
        ],
    )
    conn.commit()
    n_tracks = conn.execute("SELECT COUNT(*) FROM Track").fetchone()[0]
    n_pd = conn.execute("SELECT COUNT(*) FROM PerformanceData").fetchone()[0]
    assert n_tracks == n_pd == 2
    nulls = conn.execute(
        "SELECT COUNT(*) FROM PerformanceData WHERE trackData IS NULL"
    ).fetchone()[0]
    assert nulls == 0


def test_key_none_writes_null_track_key_and_zero_blob_key(
    conn: sqlite3.Connection,
) -> None:
    """Unknown key → Track.key NULL (no guess) but trackData key ordinal 0."""
    track = _make_track(key=None)
    insert_tracks(conn, [track])
    conn.commit()
    key = conn.execute("SELECT key FROM Track").fetchone()[0]
    assert key is None
    blob = conn.execute("SELECT trackData FROM PerformanceData").fetchone()[0]
    assert decode_track_data(blob).key == 0


def test_schema_3_0_2_insert_does_not_require_album_art_source_hash(
    tmp_path: Path,
) -> None:
    """Column-name-explicit INSERT must work when albumArtSourceHash exists but is unused.

    A positional INSERT sized for 3.0.1 would misalign on 3.0.2's extra column.
    """
    conn = _create_db(tmp_path / "m302.db", (3, 0, 2))
    try:
        cols = [r[1] for r in conn.execute("PRAGMA table_info(Track)")]
        assert "albumArtSourceHash" in cols
        insert_tracks(conn, [_make_track()])
        conn.commit()
        assert conn.execute("SELECT COUNT(*) FROM Track").fetchone()[0] == 1
        # Left at default/NULL — we do not invent a source hash.
        assert (
            conn.execute("SELECT albumArtSourceHash FROM Track").fetchone()[0] is None
        )
    finally:
        conn.close()
